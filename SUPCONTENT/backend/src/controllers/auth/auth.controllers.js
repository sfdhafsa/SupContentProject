import bcrypt from 'bcrypt';
import { validationResult } from 'express-validator';
import { UserModel } from '../../models/user.model.js';
import { signToken } from '../../utils/jwt.utils.js';

const SALT_ROUNDS = 12;

// =====================
// POST /api/auth/register
// =====================
export const register = async (req, res, next) => {
  try {
    const errors = validationResult(req);
    if (!errors.isEmpty())
      return res.status(400).json({ errors: errors.array() });

    const { email, username, password } = req.body;

    // Check email & username uniqueness
    if (await UserModel.findByEmail(email))
      return res.status(409).json({ message: 'Cet email est déjà utilisé.' });

    if (await UserModel.findByUsername(username))
      return res.status(409).json({ message: 'Ce nom d\'utilisateur est déjà pris.' });

    // Hash password
    const passwordHash = await bcrypt.hash(password, SALT_ROUNDS);

    // Create user (UUID will be generated by DB)
    const user = await UserModel.createLocal({ email, username, passwordHash });

    // Generate JWT
    const token = signToken(user.id);

    // Return safe user object (without password)
    const { password_hash, ...safeUser } = user;

    res.status(201).json({
      message: 'Compte créé avec succès.',
      token,
      user: safeUser,
    });
  } catch (err) {
    next(err);
  }
};

// =====================
// POST /api/auth/login
// =====================
export const login = async (req, res, next) => {
  try {
    const errors = validationResult(req);
    if (!errors.isEmpty())
      return res.status(400).json({ errors: errors.array() });

    const { email, password } = req.body;

    const user = await UserModel.findByEmail(email);

    // Generic error to avoid leaking info
    if (!user || !user.password_hash)
      return res.status(401).json({ message: 'Identifiants invalides.' });

    if (user.is_banned)
      return res.status(403).json({ message: 'Ce compte a été suspendu.' });

    // Compare password
    const valid = await bcrypt.compare(password, user.password_hash);
    if (!valid)
      return res.status(401).json({ message: 'Identifiants invalides.' });

    // Generate JWT
    const token = signToken(user.id);

    // Get full user info (excluding password)
    const fullUser = await UserModel.findById(user.id);
    const { password_hash, ...safeUser } = fullUser;

    res.json({
      message: 'Connexion réussie.',
      token,
      user: safeUser,
    });
  } catch (err) {
    next(err);
  }
};

// =====================
// GET /api/auth/me
// =====================
export const getMe = async (req, res, next) => {
  try {
    const user = await UserModel.findById(req.user.id);
    if (!user)
      return res.status(404).json({ message: 'Utilisateur introuvable.' });

    const { password_hash, ...safeUser } = user;
    res.json({ user: safeUser });
  } catch (err) {
    next(err);
  }
};

// =====================
// OAuth callback
// =====================
export const oauthCallback = (req, res) => {
  // Passport injects req.user after successful OAuth
  const token = signToken(req.user.id);
  res.redirect(`${process.env.CLIENT_URL}/auth/callback?token=${token}`);
};